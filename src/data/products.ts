import type { Product, ProductAvailability } from "@/types/product"
import { slugify } from "@/utils/slug"
import { photos } from "./photos"

const product = (
  id: string,
  name: string,
  category: Product["category"],
  firstDayPrice: number,
  originalPrice: number,
  additionalDayPrice: number,
  status: ProductAvailability,
  colors: string[],
  sizes: string[],
  material: string,
  imageIndexes: number[],
  isFeatured = false,
): Product => {
  const images = imageIndexes.map((index, position) => ({
    id: `${id}-image-${position + 1}`,
    url: photos[index],
    name: `${name} ${position + 1}`,
  }))
  return {
    id,
    slug: slugify(name),
    name,
    category,
    originalPrice,
    firstDayPrice,
    additionalDayPrice,
    description:
      "Phom áo mềm mại, tôn dáng với đường nét thủ công tinh tế. Một thiết kế thanh nhã cho những ngày thật đáng nhớ.",
    sizes,
    colors,
    material,
    accessories: category === "Áo dài" ? "Mấn đồng điệu" : "Không kèm phụ kiện",
    images,
    coverImage: images[0].id,
    status,
    isFeatured,
    createdAt: `2026-0${(Number(id) % 2) + 1}-${String(Number(id) + 8).padStart(2, "0")}T09:00:00.000Z`,
    updatedAt: "2026-03-18T09:00:00.000Z",
  }
}

